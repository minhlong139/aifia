export function getReport(symbol: string, date: string): string | null {
  return reports[`${symbol}:${date}`] || null
}

export function listReports(symbol: string): Array<{ date: string; title: string }> {
  const prefix = `${symbol}:`
  return Object.keys(reports)
    .filter(k => k.startsWith(prefix))
    .map(k => ({
      date: k.slice(prefix.length),
      title: `Phân tích chuyên sâu ngày ${k.slice(prefix.length).split('-').reverse().join('/')}`,
    }))
    .sort((a, b) => b.date.localeCompare(a.date))
}
